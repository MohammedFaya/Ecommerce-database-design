-- Query 4: Count total reservations by status with total revenue
SELECT 
    status,
    COUNT(*) AS total_reservations,
    SUM(total_amount) AS total_revenue,
    AVG(total_amount) AS avg_rental_cost,
    MIN(total_amount) AS min_rental_cost,
    MAX(total_amount) AS max_rental_cost
FROM RESERVATION
GROUP BY status
ORDER BY total_revenue DESC;

-- Query 5: Find vehicle categories with average daily rate above $50
SELECT 
    vc.category_name,
    COUNT(v.vehicle_id) AS vehicle_count,
    AVG(v.daily_rate) AS avg_daily_rate,
    MIN(v.daily_rate) AS min_rate,
    MAX(v.daily_rate) AS max_rate
FROM VEHICLE_CATEGORY vc
JOIN VEHICLE v ON vc.category_id = v.category_id
GROUP BY vc.category_name
HAVING AVG(v.daily_rate) > 50
ORDER BY avg_daily_rate DESC;

-- Query 6: Calculate total maintenance costs per vehicle for vehicles with costs over $500
SELECT 
    v.vehicle_id,
    v.registration_number,
    v.make,
    v.model,
    COUNT(m.maintenance_id) AS maintenance_count,
    SUM(m.cost) AS total_maintenance_cost,
    AVG(m.cost) AS avg_maintenance_cost
FROM VEHICLE v
JOIN MAINTENANCE m ON v.vehicle_id = m.vehicle_id
GROUP BY v.vehicle_id, v.registration_number, v.make, v.model
HAVING SUM(m.cost) > 500
ORDER BY total_maintenance_cost DESC;

-- Query 7: Show total revenue generated by each customer type
SELECT 
    c.customer_type,
    COUNT(DISTINCT c.customer_id) AS customer_count,
    COUNT(r.reservation_id) AS total_reservations,
    SUM(p.amount) AS total_revenue,
    AVG(p.amount) AS avg_payment
FROM CUSTOMER c
JOIN RESERVATION r ON c.customer_id = r.customer_id
JOIN PAYMENT p ON r.reservation_id = p.reservation_id
GROUP BY c.customer_type
ORDER BY total_revenue DESC;

-- ============================================
-- MULTI-TABLE JOIN QUERIES (4 minimum)
-- ============================================

-- Query 8: Show complete reservation details with customer, vehicle, and employee information
SELECT 
    r.reservation_id,
    c.first_name || ' ' || c.last_name AS customer_name,
    c.email AS customer_email,
    v.make || ' ' || v.model AS vehicle,
    v.registration_number,
    vc.category_name,
    e.first_name || ' ' || e.last_name AS processed_by,
    r.pickup_date,
    r.return_date,
    r.total_amount,
    r.status
FROM RESERVATION r
JOIN CUSTOMER c ON r.customer_id = c.customer_id
JOIN VEHICLE v ON r.vehicle_id = v.vehicle_id
JOIN VEHICLE_CATEGORY vc ON v.category_id = vc.category_id
JOIN EMPLOYEE e ON r.employee_id = e.employee_id
ORDER BY r.reservation_date DESC;

-- Query 9: List all payments with associated reservation and customer details
SELECT 
    p.payment_id,
    p.transaction_id,
    c.first_name || ' ' || c.last_name AS customer_name,
    r.reservation_id,
    v.make || ' ' || v.model AS vehicle,
    p.payment_date,
    p.amount,
    p.payment_method,
    p.payment_status,
    p.late_fee,
    p.damage_charge,
    (p.amount + p.late_fee + p.damage_charge) AS total_paid
FROM PAYMENT p
JOIN CUSTOMER c ON p.customer_id = c.customer_id
JOIN RESERVATION r ON p.reservation_id = r.reservation_id
JOIN VEHICLE v ON r.vehicle_id = v.vehicle_id
WHERE p.payment_status = 'Completed'
ORDER BY p.payment_date DESC;

-- Query 10: Show maintenance history with vehicle and employee details
SELECT 
    m.maintenance_id,
    v.registration_number,
    v.make || ' ' || v.model AS vehicle,
    vc.category_name,
    m.maintenance_type,
    m.maintenance_date,
    e.first_name || ' ' || e.last_name AS technician,
    e.department,
    m.cost,
    m.status,
    m.description
FROM MAINTENANCE m
JOIN VEHICLE v ON m.vehicle_id = v.vehicle_id
JOIN VEHICLE_CATEGORY vc ON v.category_id = vc.category_id
JOIN EMPLOYEE e ON m.employee_id = e.employee_id
WHERE m.status = 'Completed'
ORDER BY m.maintenance_date DESC;

-- Query 11: Find customers with their total spending and number of rentals
SELECT 
    c.customer_id,
    c.first_name || ' ' || c.last_name AS customer_name,
    c.customer_type,
    COUNT(r.reservation_id) AS total_rentals,
    SUM(p.amount + p.late_fee + p.damage_charge) AS total_spent,
    AVG(p.amount) AS avg_rental_cost
FROM CUSTOMER c
JOIN RESERVATION r ON c.customer_id = r.customer_id
JOIN PAYMENT p ON r.reservation_id = p.reservation_id
GROUP BY c.customer_id, c.first_name, c.last_name, c.customer_type
ORDER BY total_spent DESC;

-- ============================================
-- SUBQUERY QUERIES (3 minimum)
-- ============================================

-- Query 12: Find vehicles that have never been rented
SELECT 
    v.vehicle_id,
    v.registration_number,
    v.make,
    v.model,
    v.year,
    vc.category_name,
    v.daily_rate,
    v.status
FROM VEHICLE v
JOIN VEHICLE_CATEGORY vc ON v.category_id = vc.category_id
WHERE v.vehicle_id NOT IN (
    SELECT DISTINCT vehicle_id 
    FROM RESERVATION
)
ORDER BY v.daily_rate DESC;

-- Query 13: Find customers who have spent more than the average customer
SELECT 
    c.customer_id,
    c.first_name || ' ' || c.last_name AS customer_name,
    c.email,
    c.customer_type,
    SUM(p.amount + p.late_fee + p.damage_charge) AS total_spent
FROM CUSTOMER c
JOIN RESERVATION r ON c.customer_id = r.customer_id
JOIN PAYMENT p ON r.reservation_id = p.reservation_id
GROUP BY c.customer_id, c.first_name, c.last_name, c.email, c.customer_type
HAVING SUM(p.amount + p.late_fee + p.damage_charge) > (
    SELECT AVG(total_payment)
    FROM (
        SELECT SUM(amount + late_fee + damage_charge) AS total_payment
        FROM PAYMENT
        GROUP BY customer_id
    ) AS customer_totals
)
ORDER BY total_spent DESC;

-- Query 14: List vehicles with maintenance costs above category average
SELECT 
    v.vehicle_id,
    v.registration_number,
    v.make || ' ' || v.model AS vehicle,
    vc.category_name,
    COALESCE(SUM(m.cost), 0) AS total_maintenance_cost
FROM VEHICLE v
JOIN VEHICLE_CATEGORY vc ON v.category_id = vc.category_id
LEFT JOIN MAINTENANCE m ON v.vehicle_id = m.vehicle_id
GROUP BY v.vehicle_id, v.registration_number, v.make, v.model, vc.category_name, v.category_id
HAVING COALESCE(SUM(m.cost), 0) > (
    SELECT AVG(cat_cost)
    FROM (
        SELECT SUM(m2.cost) AS cat_cost
        FROM VEHICLE v2
        LEFT JOIN MAINTENANCE m2 ON v2.vehicle_id = m2.vehicle_id
        WHERE v2.category_id = v.category_id
        GROUP BY v2.vehicle_id
    ) AS category_costs
)
ORDER BY total_maintenance_cost DESC;


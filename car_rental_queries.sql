-- Query 15: Calculate rental duration and cost efficiency for completed reservations
SELECT 
    r.reservation_id,
    c.first_name || ' ' || c.last_name AS customer_name,
    v.make || ' ' || v.model AS vehicle,
    r.pickup_date,
    r.return_date,
    r.actual_return_date,
    (r.actual_return_date - r.pickup_date) AS actual_duration_days,
    (r.return_date - r.pickup_date) AS planned_duration_days,
    r.total_amount,
    ROUND(r.total_amount / NULLIF(r.actual_return_date - r.pickup_date, 0), 2) AS cost_per_day,
    CASE 
        WHEN r.actual_return_date > r.return_date THEN 'Late Return'
        WHEN r.actual_return_date < r.return_date THEN 'Early Return'
        ELSE 'On Time'
    END AS return_status
FROM RESERVATION r
JOIN CUSTOMER c ON r.customer_id = c.customer_id
JOIN VEHICLE v ON r.vehicle_id = v.vehicle_id
WHERE r.status = 'Completed' AND r.actual_return_date IS NOT NULL
ORDER BY r.pickup_date DESC;

-- Query 16: Find customers whose licenses expire within the next 6 months
SELECT 
    customer_id,
    first_name || ' ' || last_name AS customer_name,
    email,
    phone,
    license_number,
    license_expiry,
    (license_expiry - CURRENT_DATE) AS days_until_expiry,
    CASE 
        WHEN license_expiry - CURRENT_DATE <= 30 THEN 'Urgent'
        WHEN license_expiry - CURRENT_DATE <= 90 THEN 'Soon'
        ELSE 'Moderate'
    END AS urgency_level
FROM CUSTOMER
WHERE license_expiry <= CURRENT_DATE + INTERVAL '6 months'
ORDER BY license_expiry;

-- Query 17: Analyze monthly revenue trends
SELECT 
    TO_CHAR(p.payment_date, 'YYYY-MM') AS year_month,
    TO_CHAR(p.payment_date, 'Month YYYY') AS month_name,
    COUNT(DISTINCT p.payment_id) AS total_payments,
    COUNT(DISTINCT r.reservation_id) AS total_reservations,
    SUM(p.amount + p.late_fee + p.damage_charge) AS total_revenue,
    AVG(p.amount) AS avg_payment,
    SUM(p.late_fee) AS total_late_fees,
    SUM(p.damage_charge) AS total_damage_charges
FROM PAYMENT p
JOIN RESERVATION r ON p.reservation_id = r.reservation_id
WHERE p.payment_status = 'Completed'
GROUP BY TO_CHAR(p.payment_date, 'YYYY-MM'), TO_CHAR(p.payment_date, 'Month YYYY')
ORDER BY year_month DESC;


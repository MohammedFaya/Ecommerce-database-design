-- Query 18: Rank vehicles by total revenue generated using window functions
SELECT 
    v.vehicle_id,
    v.registration_number,
    v.make || ' ' || v.model AS vehicle,
    vc.category_name,
    COUNT(r.reservation_id) AS rental_count,
    SUM(r.total_amount) AS total_revenue,
    AVG(r.total_amount) AS avg_rental_value,
    RANK() OVER (ORDER BY SUM(r.total_amount) DESC) AS revenue_rank,
    RANK() OVER (PARTITION BY vc.category_name ORDER BY SUM(r.total_amount) DESC) AS category_rank
FROM VEHICLE v
JOIN VEHICLE_CATEGORY vc ON v.category_id = vc.category_id
LEFT JOIN RESERVATION r ON v.vehicle_id = r.vehicle_id
GROUP BY v.vehicle_id, v.registration_number, v.make, v.model, vc.category_name
ORDER BY total_revenue DESC NULLS LAST;

-- Query 19: Use CTE to find employee performance metrics
WITH EmployeeStats AS (
    SELECT 
        e.employee_id,
        e.first_name || ' ' || e.last_name AS employee_name,
        e.department,
        e.position,
        COUNT(DISTINCT r.reservation_id) AS reservations_processed,
        COALESCE(SUM(r.total_amount), 0) AS total_reservation_value,
        COUNT(DISTINCT m.maintenance_id) AS maintenance_tasks,
        COALESCE(SUM(m.cost), 0) AS total_maintenance_cost
    FROM EMPLOYEE e
    LEFT JOIN RESERVATION r ON e.employee_id = r.employee_id
    LEFT JOIN MAINTENANCE m ON e.employee_id = m.employee_id
    WHERE e.status = 'Active'
    GROUP BY e.employee_id, e.first_name, e.last_name, e.department, e.position
)
SELECT 
    employee_name,
    department,
    position,
    reservations_processed,
    maintenance_tasks,
    (reservations_processed + maintenance_tasks) AS total_activities,
    total_reservation_value,
    total_maintenance_cost,
    ROUND((total_reservation_value / NULLIF(reservations_processed, 0)), 2) AS avg_reservation_value,
    RANK() OVER (ORDER BY (reservations_processed + maintenance_tasks) DESC) AS productivity_rank
FROM EmployeeStats
ORDER BY total_activities DESC;

-- Query 20: Advanced correlated subquery to find most popular vehicle in each category
SELECT DISTINCT
    vc.category_name,
    v.vehicle_id,
    v.registration_number,
    v.make || ' ' || v.model AS vehicle,
    (
        SELECT COUNT(*)
        FROM RESERVATION r
        WHERE r.vehicle_id = v.vehicle_id
    ) AS rental_count,
    v.daily_rate
FROM VEHICLE v
JOIN VEHICLE_CATEGORY vc ON v.category_id = vc.category_id
WHERE (
    SELECT COUNT(*)
    FROM RESERVATION r
    WHERE r.vehicle_id = v.vehicle_id
) = (
    SELECT MAX(rental_count)
    FROM (
        SELECT COUNT(*) AS rental_count
        FROM RESERVATION r2
        JOIN VEHICLE v2 ON r2.vehicle_id = v2.vehicle_id
        WHERE v2.category_id = v.category_id
        GROUP BY r2.vehicle_id
    ) AS category_rentals
)
ORDER BY vc.category_name;
-- ============================================
-- SIMPLE SELECT + FILTERING/SORTING QUERIES (3 minimum)
-- ============================================

-- Query 1: List all available vehicles sorted by daily rate (ascending)
SELECT 
    vehicle_id,
    registration_number,
    make,
    model,
    year,
    color,
    daily_rate,
    status
FROM VEHICLE
WHERE status = 'Available'
ORDER BY daily_rate ASC;

-- Query 2: Find all VIP customers who registered in 2023
SELECT 
    customer_id,
    first_name,
    last_name,
    email,
    phone,
    registration_date,
    customer_type
FROM CUSTOMER
WHERE customer_type = 'VIP' 
    AND EXTRACT(YEAR FROM registration_date) = 2023
ORDER BY registration_date;

-- Query 3: List all luxury vehicles manufactured after 2023
SELECT 
    v.vehicle_id,
    v.make,
    v.model,
    v.year,
    v.color,
    v.daily_rate,
    vc.category_name
FROM VEHICLE v
JOIN VEHICLE_CATEGORY vc ON v.category_id = vc.category_id
WHERE vc.category_name = 'Luxury' 
    AND v.year > 2023
ORDER BY v.daily_rate DESC;

-- ============================================
